#!/usr/bin/env python3
"""Build a plain-Luau test tree from the Rojo source tree.

Roblox modules reference siblings as `require(script.Parent.X)`; the standalone
Luau CLI uses string paths. This rewrites only that pattern so the *same files*
that ship in the game are the ones under test (no forked copies).
"""
import re
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SHARED = ROOT / "src" / "shared"
TESTS = ROOT / "tests"
BUILD = TESTS / ".build"

REQUIRE_RE = re.compile(r"require\(\s*script\.Parent\.(\w+)\s*\)")


INJECT = {
    "Vector3": 'local Vector3 = require("./__Stubs").Vector3',
    "Color3": 'local Color3 = require("./__Stubs").Color3',
}


def rewrite(source: str) -> str:
    """Rewrite sibling requires and inject the stubbed Roblox value types."""
    source = REQUIRE_RE.sub(lambda m: f'require("./{m.group(1)}")', source)
    lines = source.split("\n")
    inject = [stmt for name, stmt in INJECT.items() if re.search(rf"\b{name}\b", source)]
    if not inject:
        return source
    # Keep `--!strict` as the very first line, then inject.
    if lines and lines[0].startswith("--!"):
        return "\n".join([lines[0]] + inject + lines[1:])
    return "\n".join(inject + lines)


def main() -> int:
    if BUILD.exists():
        shutil.rmtree(BUILD)
    (BUILD / "shared").mkdir(parents=True)
    (BUILD / "support").mkdir()
    (BUILD / "specs").mkdir()

    rewritten = 0
    for path in sorted(SHARED.glob("*.luau")):
        text = path.read_text(encoding="utf-8")
        new = rewrite(text)
        if new != text:
            rewritten += 1
        (BUILD / "shared" / path.name).write_text(new, encoding="utf-8")

    for path in sorted((TESTS / "support").glob("*.luau")):
        shutil.copy2(path, BUILD / "support" / path.name)

    # Shared modules that touch Vector3/Color3 require the stubs relatively.
    shutil.copy2(TESTS / "support" / "Stubs.luau", BUILD / "shared" / "__Stubs.luau")

    specs = sorted((TESTS / "specs").glob("*.luau"))
    for path in specs:
        shutil.copy2(path, BUILD / "specs" / path.name)

    runner = [
        "-- generated by tools/test_build.py -- do not edit",
        'local T = require("./support/TinyTest")',
        'print("\\nECHOWAKE unit tests (" .. tostring(' + str(len(specs)) + ') .. " spec files)")',
    ]
    for path in specs:
        runner.append(f'require("./specs/{path.stem}")')
    runner.append("local code = T.report()")
    runner.append('print(code == 0 and "RESULT: PASS" or "RESULT: FAIL")')
    (BUILD / "run.luau").write_text("\n".join(runner) + "\n", encoding="utf-8")

    print(f"built {len(specs)} specs, rewrote {rewritten} shared modules -> {BUILD}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
